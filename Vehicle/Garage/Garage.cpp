#include "Garage.h"
#include "main.h"
#include "fdcan.h"
#include "usart.h"

namespace garage
{

/***********************************************************************
** 函 数 名： Garage::Garage()
** 函数说明： 聚合类构造，成员各自构造
**---------------------------------------------------------------------
** 输入参数： 无
** 返回参数： 无
***********************************************************************/
Garage::Garage()
{
}

/***********************************************************************
** 函 数 名： bool Garage::init()
** 函数说明： 初始化各任务
**---------------------------------------------------------------------
** 输入参数： 无
** 返回参数： true：成功；false：失败
***********************************************************************/
bool Garage::init()
{
    if (!battRotate.init(hfdcan1, huart6))
    {
        return false;
    }
    return battPush.init(hfdcan2);
}

/***********************************************************************
** 函 数 名： Garage::battRotateUpdate()
** 函数说明： 执行一轮电池旋转任务更新
**---------------------------------------------------------------------
** 输入参数： 无
** 返回参数： 无
***********************************************************************/
void Garage::battRotateUpdate()
{
    battRotate.update();
}

/***********************************************************************
** 函 数 名： Garage::battPushUpdate()
** 函数说明： 执行一轮电池推送任务更新
**---------------------------------------------------------------------
** 输入参数： 无
** 返回参数： 无
***********************************************************************/
void Garage::battPushUpdate()
{
    battPush.update();
}

}
